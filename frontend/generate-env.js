#!/usr/bin/env node
// Vercel build script: generates env-config.js from environment variables.
// Vercel runs this as the "Build Command": node generate-env.js
const fs = require('fs');

const apiBaseUrl = process.env.API_BASE_URL || '';

const content = `// Auto-generated by generate-env.js during Vercel build. Do not edit.
window.__ENV__ = {
  API_BASE_URL: "${apiBaseUrl.replace(/"/g, '\\"')}"
};
`;

fs.writeFileSync('./env-config.js', content);
console.log(`[generate-env] API_BASE_URL = "${apiBaseUrl}"`);
console.log('[generate-env] env-config.js written successfully.');
